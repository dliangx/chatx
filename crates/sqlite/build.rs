//! Scans `migrations/*.sql` (lexicographic order) and emits a Rust static
//! of (version, sql) pairs so that `lib.rs` doesn't need to list files.
//!
//! Convention: filename starts with a numeric version prefix — `0001_foo.sql`
//! becomes version 1, `0002_bar.sql` becomes version 2, etc.
//!
//! To add a new migration: drop a `NNNN_name.sql` file into `migrations/`.
//! cargo will pick it up automatically thanks to the `rerun-if-changed`.

use std::env;
use std::fs;
use std::path::Path;

fn main() {
    let manifest = env::var("CARGO_MANIFEST_DIR").unwrap();
    let migrations_dir = Path::new(&manifest).join("migrations");
    if !migrations_dir.is_dir() {
        // No migrations dir = nothing to do. `lib.rs` will still compile
        // against an empty static.
        emit_empty();
        return;
    }

    let mut files: Vec<String> = fs::read_dir(&migrations_dir)
        .expect("read migrations dir")
        .filter_map(|e| e.ok())
        .map(|e| e.file_name().to_string_lossy().to_string())
        .filter(|f| f.ends_with(".sql"))
        .collect();
    files.sort(); // lexicographic == version-ordered for zero-padded prefixes.

    let mut out = String::new();
    out.push_str("// Auto-generated by build.rs — do not edit.\n");
    out.push_str("#[allow(dead_code)]\n");
    out.push_str("pub static MIGRATIONS: &[(u32, &str)] = &[\n");
    for file in &files {
        let stem = file.strip_suffix(".sql").unwrap_or(file);
        let version_str = stem.split('_').next().unwrap_or("0");
        let version: u32 = version_str.parse().unwrap_or(0);
        let abs = format!("{}/migrations/{}", manifest, file);
        out.push_str(&format!("    ({version}u32, include_str!( \"{abs}\" )),\n"));
    }
    out.push_str("];\n");

    let out_dir = env::var("OUT_DIR").unwrap();
    fs::write(Path::new(&out_dir).join("migrations_generated.rs"), out)
        .expect("write generated migrations");

    println!("cargo:rerun-if-changed=migrations");
}

fn emit_empty() {
    let out_dir = env::var("OUT_DIR").unwrap();
    let body = "\
// Auto-generated by build.rs — do not edit.
#[allow(dead_code)]
pub static MIGRATIONS: &[(u32, &str)] = &[];
";
    fs::write(std::path::Path::new(&out_dir).join("migrations_generated.rs"), body)
        .expect("write generated migrations");
    println!("cargo:rerun-if-changed=migrations");
}
