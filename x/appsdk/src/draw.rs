//! 5×7 bitmap text (P0 text primitive — ASCII only, lowercase falls back to
//! small caps).
//!
//! P1 replaces this with a `fontdue` + `rustybuzz` rasterizer matching the
//! host's chat-bubble compositor (CJK, proper case, shaping); the
//! `Ctx::fill_text` call-site stays the same.

use crate::ctx::Ctx;

pub(crate) struct FontPen<'a> {
    pub(crate) ctx: &'a mut Ctx,
    pub(crate) y: i32,
    pub(crate) scale: i32,
    pub(crate) color: u32,
}

/// Draw one character at `x` (scale from the pen), return the next x.
pub(crate) fn draw_char(pen: &mut FontPen, c: char, x: i32) -> i32 {
    let Ok(code) = u8::try_from(c as u32) else {
        return x + 6 * pen.scale; // placeholder advance for non-ASCII
    };
    if !(32..127).contains(&code) {
        return x + 6 * pen.scale;
    }
    let rows = ALL[(code as usize) - 32];
    let scale = pen.scale;
    for (ry, row) in rows.iter().enumerate() {
        for col in 0..5i32 {
            let bit = 1 << (4 - col);
            if row & bit != 0 {
                let px = (x + col * scale) as isize;
                let py = (pen.y as i32 + (ry as i32) * scale) as isize;
                for dy in 0..scale {
                    for dx in 0..scale {
                        pen.ctx.set_px(px + dx as isize, py + dy as isize, pen.color);
                    }
                }
            }
        }
    }
    x + 6 * scale // 5 dots + 1 gap
}

